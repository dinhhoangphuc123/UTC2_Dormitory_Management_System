// Generate 48 rooms across Buildings A01, A02, A03, B01, B02, C01
export function generateRooms(): Room[] {
  const buildings = [
    { id: 'A01', name: 'Tòa A01', gender: 'Nam' as const, floors: 4, roomsPerFloor: 4 },
    { id: 'A02', name: 'Tòa A02', gender: 'Nam' as const, floors: 4, roomsPerFloor: 3 },
    { id: 'B01', name: 'Tòa B01', gender: 'Nữ' as const, floors: 4, roomsPerFloor: 3 },
    { id: 'B02', name: 'Tòa B02', gender: 'Nữ' as const, floors: 4, roomsPerFloor: 3 },
    { id: 'C01', name: 'Tòa C01', gender: 'Nam' as const, floors: 3, roomsPerFloor: 3 },
  ];

  const rooms: Room[] = [];
  let count = 0;

  for (const b of buildings) {
    for (let f = 1; f <= b.floors; f++) {
      for (let r = 1; r <= b.roomsPerFloor; r++) {
        if (count >= 48) break;
        count++;
        const roomNum = `${b.id.substring(0, 1)}${f}0${r}`;
        const isMaintenance = count === 12; // 1 room under maintenance (4 beds)
        const occupiedCount = isMaintenance ? 0 : (count % 5 === 0 ? 7 : (count % 3 === 0 ? 6 : 8));

        const beds = Array.from({ length: 8 }, (_, i) => {
          const bedNum = `G${i + 1}`;
          if (isMaintenance && i < 4) {
            return {
              id: `${roomNum}-${bedNum}`,
              bedNumber: bedNum,
              status: 'Bảo trì' as const,
            };
          }
          if (i < occupiedCount) {
            return {
              id: `${roomNum}-${bedNum}`,
              bedNumber: bedNum,
              studentName: `Sinh viên ${roomNum}-${bedNum}`,
              mssv: `64510${count}${i}01`,
              status: 'Đang ở' as const,
            };
          }
          return {
            id: `${roomNum}-${bedNum}`,
            bedNumber: bedNum,
            status: 'Giường trống' as const,
          };
        });

        rooms.push({
          id: `room_${count}`,
          buildingId: b.id,
          buildingName: b.name,
          floor: f,
          roomNumber: roomNum,
          capacity: 8,
          occupied: occupiedCount,
          gender: b.gender,
          roomType: b.id === 'C01' ? 'Chất lượng cao' : 'Tiêu chuẩn',
          pricePerMonth: b.id === 'C01' ? 700000 : 500000,
          status: isMaintenance ? 'Bảo trì' : (occupiedCount === 8 ? 'Đầy' : 'Còn chỗ'),
          beds,
        });
      }
    }
  }

  return rooms;
}
